/**
 * GET /api/proxy?url=<upstream>&ref=<referer>&exp=<epoch-ms>&sig=<hmac>
 *
 * Streaming HLS proxy. Fetches the upstream resource server-side (so the
 * browser never hits a cross-origin CDN and CORS is a non-issue), then:
 *
 *  - `.m3u8` playlists: body is read, every URI (segments, variant playlists,
 *    `#EXT-X-KEY`, `#EXT-X-MAP`, `#EXT-X-MEDIA`, …) is rewritten to a relative
 *    `/api/proxy?...` link and the result is served as
 *    `application/vnd.apple.mpegurl` with `no-store` caching.
 *  - Everything else (TS / fMP4 segments, AES keys, WebVTT): the upstream body
 *    is piped straight to the client as it arrives — no buffering — with the
 *    upstream `Content-Type`, `Content-Length`, `Content-Range` and status
 *    (`206` for range requests) preserved. The transfer is bounded by upstream
 *    *idle* time rather than total duration so large segments on slow links
 *    are not cut off part-way.
 *
 * Links are HMAC-signed with `STREAM_SECRET` (see `lib/hlsProxy.ts`) and
 * generated by `lib/streamEngine.ts`; this route rejects unsigned requests so
 * it cannot be used as a general-purpose open proxy.
 */
import { NextRequest, NextResponse } from 'next/server';
import logger from '@/lib/logger';
import {
  HLS_PLAYLIST_MIME,
  guessContentType,
  isPlaylistContentType,
  isPlaylistUrl,
  parseSafeUpstreamUrl,
  rewritePlaylist,
  verifyProxySignature,
} from '@/lib/hlsProxy';

export const dynamic = 'force-dynamic';

/* -------------------------------------------------------------------------- */
/*  Tunables                                                                  */
/* -------------------------------------------------------------------------- */

/** Max time to wait for upstream response *headers*. */
const HEADER_TIMEOUT_MS = 20_000;
/** Max total time for a playlist download (they are tiny). */
const PLAYLIST_TIMEOUT_MS = 15_000;
/** Abort a segment transfer only if upstream goes silent this long. */
const SEGMENT_IDLE_TIMEOUT_MS = 20_000;
/** Largest playlist we are willing to parse/rewrite. */
const MAX_PLAYLIST_BYTES = 4 * 1024 * 1024;

const BROWSER_UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36';

const CORS_HEADERS: Record<string, string> = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Methods': 'GET, HEAD, OPTIONS',
  'Access-Control-Allow-Headers': 'Range, Origin, Accept, Content-Type, If-None-Match, If-Modified-Since',
  'Access-Control-Expose-Headers': 'Content-Length, Content-Range, Accept-Ranges, Content-Type, ETag, Last-Modified',
  'Access-Control-Max-Age': '86400',
};

/** Upstream response headers worth passing through for media payloads. */
const PASSTHROUGH_HEADERS = [
  'content-type',
  'content-length',
  'content-range',
  'accept-ranges',
  'etag',
  'last-modified',
  'cache-control',
  'expires',
];

/* -------------------------------------------------------------------------- */
/*  Helpers                                                                   */
/* -------------------------------------------------------------------------- */

function errorResponse(status: number, message: string, extra?: Record<string, unknown>) {
  return NextResponse.json(
    { error: message, ...extra },
    { status, headers: { ...CORS_HEADERS, 'Cache-Control': 'no-store' } }
  );
}

function buildUpstreamHeaders(request: NextRequest, target: URL, referer: string): Headers {
  const headers = new Headers();
  headers.set('User-Agent', request.headers.get('user-agent') || BROWSER_UA);
  headers.set('Accept', '*/*');
  // Ask for an uncompressed body so Content-Length / Range semantics stay exact
  // when we relay the stream (fetch would otherwise transparently gunzip it).
  headers.set('Accept-Encoding', 'identity');
  headers.set('Accept-Language', 'en-US,en;q=0.9');
  headers.set('Connection', 'keep-alive');

  let origin = target.origin;
  if (referer) {
    headers.set('Referer', referer);
    try {
      origin = new URL(referer).origin;
    } catch {
      /* keep upstream origin */
    }
  } else {
    headers.set('Referer', `${target.origin}/`);
  }
  headers.set('Origin', origin);

  // Forward byte-range requests untouched (ffmpeg-style players and
  // #EXT-X-BYTERANGE playlists depend on this).
  const range = request.headers.get('range');
  if (range) headers.set('Range', range);

  const ifNoneMatch = request.headers.get('if-none-match');
  if (ifNoneMatch) headers.set('If-None-Match', ifNoneMatch);
  const ifModifiedSince = request.headers.get('if-modified-since');
  if (ifModifiedSince) headers.set('If-Modified-Since', ifModifiedSince);

  return headers;
}

/**
 * Wrap a body stream so that the upstream request is aborted if no bytes
 * arrive for `idleMs`. Timer resets on every chunk, so slow-but-alive
 * transfers are never cut off.
 */
function withIdleTimeout(
  body: ReadableStream<Uint8Array>,
  idleMs: number,
  abort: AbortController
): ReadableStream<Uint8Array> {
  let timer: ReturnType<typeof setTimeout> | null = null;
  const clear = () => {
    if (timer) clearTimeout(timer);
    timer = null;
  };
  const arm = () => {
    clear();
    timer = setTimeout(() => abort.abort(new Error('Upstream idle timeout')), idleMs);
  };

  return body.pipeThrough(
    new TransformStream<Uint8Array, Uint8Array>({
      start: () => arm(),
      transform: (chunk, controller) => {
        arm();
        controller.enqueue(chunk);
      },
      flush: () => clear(),
      // Client disconnects propagate through pipeThrough() to the upstream
      // body (and via request.signal), so no explicit cancel hook is needed.
    })
  );
}

const EXTM3U = new TextEncoder().encode('#EXTM3U');

function startsWithExtM3u(bytes: Uint8Array): boolean {
  // Tolerate a UTF-8 BOM.
  let offset = 0;
  if (bytes.length >= 3 && bytes[0] === 0xef && bytes[1] === 0xbb && bytes[2] === 0xbf) offset = 3;
  if (bytes.length < offset + EXTM3U.length) return false;
  for (let i = 0; i < EXTM3U.length; i++) {
    if (bytes[offset + i] !== EXTM3U[i]) return false;
  }
  return true;
}

/**
 * Peek at the first chunk of a stream (to sniff `#EXTM3U`) and return a new
 * stream that still yields every byte, starting with the peeked chunk.
 */
async function peekStream(
  body: ReadableStream<Uint8Array>
): Promise<{ head: Uint8Array | null; stream: ReadableStream<Uint8Array> }> {
  const reader = body.getReader();
  const first = await reader.read();
  const head = first.done ? null : first.value;

  const stream = new ReadableStream<Uint8Array>({
    start(controller) {
      if (head) controller.enqueue(head);
      if (first.done) controller.close();
    },
    async pull(controller) {
      const { done, value } = await reader.read();
      if (done) controller.close();
      else controller.enqueue(value);
    },
    cancel(reason) {
      return reader.cancel(reason);
    },
  });

  return { head, stream };
}

async function readAllLimited(stream: ReadableStream<Uint8Array>, limit: number): Promise<Uint8Array> {
  const reader = stream.getReader();
  const chunks: Uint8Array[] = [];
  let total = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    total += value.byteLength;
    if (total > limit) {
      await reader.cancel();
      throw new Error('Playlist exceeds size limit');
    }
    chunks.push(value);
  }
  const out = new Uint8Array(total);
  let offset = 0;
  for (const c of chunks) {
    out.set(c, offset);
    offset += c.byteLength;
  }
  return out;
}

