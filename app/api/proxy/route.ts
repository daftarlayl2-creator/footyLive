export async function OPTIONS() {
  return new NextResponse(null, { status: 204, headers: CORS_HEADERS });
}

export async function GET(request: NextRequest) {
  const { searchParams } = request.nextUrl;
  const rawUrl = searchParams.get('url');
  const referer = searchParams.get('ref') || '';
  const exp = Number(searchParams.get('exp'));
  const sig = searchParams.get('sig') || '';
  const clientIp = request.headers.get('x-forwarded-for') || 'unknown';

  if (!rawUrl) return errorResponse(400, 'Missing "url" parameter');

  if (!verifyProxySignature(rawUrl, referer, exp, sig)) {
    logger.warn('HLS proxy: signature mismatch', { url: rawUrl, ip: clientIp });
    return errorResponse(403, 'Invalid signature');
  }
  if (exp < Date.now()) {
    logger.warn('HLS proxy: link expired', { url: rawUrl, exp, ip: clientIp });
    return errorResponse(403, 'Stream link has expired');
  }

  const target = parseSafeUpstreamUrl(rawUrl);
  if (!target) {
    logger.warn('HLS proxy: refused unsafe upstream URL', { url: rawUrl, ip: clientIp });
    return errorResponse(400, 'Unsupported or unsafe upstream URL');
  }

  const abort = new AbortController();
  // Tear down the upstream fetch if the player navigates away / cancels.
  request.signal.addEventListener('abort', () => abort.abort(new Error('Client aborted')), { once: true });

  const headerTimer = setTimeout(() => abort.abort(new Error('Upstream header timeout')), HEADER_TIMEOUT_MS);

  let upstream: Response;
  try {
    upstream = await fetch(target.toString(), {
      method: 'GET',
      headers: buildUpstreamHeaders(request, target, referer),
      redirect: 'follow',
      signal: abort.signal,
      cache: 'no-store',
    });
  } catch (err) {
    clearTimeout(headerTimer);
    if (request.signal.aborted) return new NextResponse(null, { status: 499 });
    logger.error('HLS proxy: upstream fetch failed', err, { url: target.toString() });
    return errorResponse(502, 'Upstream fetch failed');
  } finally {
    clearTimeout(headerTimer);
  }

  const finalUrl = upstream.url || target.toString();
  const upstreamType = upstream.headers.get('content-type');

  // Pass through non-success statuses (404/403/304…) so hls.js can react, but
  // never leak upstream 5xx HTML pages as-is.
  if (!upstream.ok && upstream.status !== 206 && upstream.status !== 304) {
    const status = upstream.status >= 500 ? 502 : upstream.status;
    logger.warn('HLS proxy: upstream returned error status', { url: finalUrl, status: upstream.status });
    upstream.body?.cancel().catch(() => {});
    return errorResponse(status, `Upstream responded with ${upstream.status}`);
  }

  if (upstream.status === 304 || !upstream.body) {
    const headers = new Headers(CORS_HEADERS);
    for (const h of ['etag', 'last-modified', 'cache-control']) {
      const v = upstream.headers.get(h);
      if (v) headers.set(h, v);
    }
    return new NextResponse(null, { status: upstream.status, headers });
  }

  /* ----------------------------- Playlist path ---------------------------- */

  let treatAsPlaylist = isPlaylistContentType(upstreamType) || isPlaylistUrl(finalUrl);
  let body: ReadableStream<Uint8Array> = upstream.body;

  // Many sports CDNs serve playlists from `.php`/extension-less endpoints with
  // text/plain or octet-stream. Sniff the first bytes when in doubt.
  if (!treatAsPlaylist && upstream.status === 200) {
    const lower = (upstreamType || '').toLowerCase();
    const ambiguous = !lower || lower.includes('text/') || lower.includes('octet-stream') || lower.includes('json');
    if (ambiguous) {
      const peeked = await peekStream(upstream.body);
      body = peeked.stream;
      if (peeked.head && startsWithExtM3u(peeked.head)) treatAsPlaylist = true;
    }
  }

  if (treatAsPlaylist) {
    const playlistTimer = setTimeout(() => abort.abort(new Error('Playlist timeout')), PLAYLIST_TIMEOUT_MS);
    let text: string;
    try {
      const bytes = await readAllLimited(body, MAX_PLAYLIST_BYTES);
      text = new TextDecoder('utf-8').decode(bytes);
    } catch (err) {
      if (request.signal.aborted) return new NextResponse(null, { status: 499 });
      logger.error('HLS proxy: failed reading playlist', err, { url: finalUrl });
      return errorResponse(502, 'Failed reading upstream playlist');
    } finally {
      clearTimeout(playlistTimer);
    }

    if (!text.trimStart().startsWith('#EXTM3U')) {
      logger.warn('HLS proxy: upstream playlist is not valid M3U8', { url: finalUrl, contentType: upstreamType });
      return errorResponse(502, 'Upstream did not return a valid HLS playlist');
    }

    const rewritten = rewritePlaylist(text, finalUrl, { referer });

    return new NextResponse(rewritten, {
      status: 200,
      headers: {
        ...CORS_HEADERS,
        'Content-Type': HLS_PLAYLIST_MIME,
        'Cache-Control': 'no-store, no-cache, must-revalidate',
        Pragma: 'no-cache',
        'X-Proxy-Upstream': target.hostname,
      },
    });
  }

  /* ------------------------------ Segment path ---------------------------- */

  const headers = new Headers(CORS_HEADERS);
  for (const name of PASSTHROUGH_HEADERS) {
    const value = upstream.headers.get(name);
    if (value) headers.set(name, value);
  }
  if (!headers.has('content-type')) {
    const guessed = guessContentType(finalUrl);
    if (guessed) headers.set('Content-Type', guessed);
  }
  if (!headers.has('cache-control')) {
    // Media segments are immutable once published; keys/init segments too.
    headers.set('Cache-Control', 'public, max-age=300');
  }
  if (!headers.has('accept-ranges')) headers.set('Accept-Ranges', 'bytes');
  headers.set('X-Proxy-Upstream', target.hostname);

  // Relay as it arrives: status (200/206) and headers intact.
  return new NextResponse(withIdleTimeout(body, SEGMENT_IDLE_TIMEOUT_MS, abort), {
    status: upstream.status,
    headers,
  });
}
